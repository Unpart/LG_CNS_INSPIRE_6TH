const BeachMap = ({ selectedCode, onSelect }) => {
    const containerRef = useRef(null);
    const mapRef = useRef(null);
    const markersRef = useRef([]);
    const selectionRef = useRef(selectedCode);
    const onSelectRef = useRef(onSelect);
    const [status, setStatus] = useState("loading");
    const [attempt, setAttempt] = useState(0);
    useEffect(() => { onSelectRef.current = onSelect; }, [onSelect]);
    useEffect(() => { selectionRef.current = selectedCode; }, [selectedCode]);

    useEffect(() => {
        let disposed = false;
        let observer;
        let timer;
        const listeners = [];
        const overlays = [];
        const maps = window.kakao?.maps;
        const fail = () => { if (!disposed) setStatus("error"); };
        setStatus("loading");
        if (!maps?.load) { fail(); return undefined; }
        timer = window.setTimeout(fail, 12000);
        try {
            maps.load(() => {
                if (disposed) return;
                try {
                    const initial = BEACHES.find((beach) => beach.code === selectionRef.current);
                    const map = new maps.Map(containerRef.current, {
                        center: new maps.LatLng(initial.lat, initial.lng), level: 6,
                    });
                    mapRef.current = map;
                    map.addControl(new maps.ZoomControl(), maps.ControlPosition.RIGHT);
                    const listen = (target, type, handler) => {
                        maps.event.addListener(target, type, handler);
                        listeners.push([target, type, handler]);
                    };
                    markersRef.current = BEACHES.map((beach) => {
                        const marker = new maps.Marker({
                            map, position: new maps.LatLng(beach.lat, beach.lng), title: beachLabel(beach),
                        });
                        overlays.push(marker);
                        const choose = () => onSelectRef.current(beach.code);
                        listen(marker, "click", choose);
                        return { code: beach.code, marker };
                    });
                    if (window.ResizeObserver) {
                        observer = new ResizeObserver(() => {
                            const center = map.getCenter();
                            map.relayout();
                            map.setCenter(center);
                        });
                        observer.observe(containerRef.current);
                    }
                    window.clearTimeout(timer);
                    setStatus("ready");
                } catch { fail(); }
            });
        } catch { fail(); }
        return () => {
            disposed = true;
            window.clearTimeout(timer);
            observer?.disconnect();
            listeners.forEach(([target, type, handler]) => maps.event.removeListener(target, type, handler));
            overlays.forEach((overlay) => overlay.setMap(null));
            markersRef.current = [];
            mapRef.current = null;
        };
    }, [attempt]);

    useEffect(() => {
        if (status !== "ready" || !mapRef.current) return;
        const maps = window.kakao.maps;
        const beach = BEACHES.find((entry) => entry.code === selectedCode);
        markersRef.current.forEach(({ code, marker }) => {
            const active = code === selectedCode;
            marker.setZIndex(active ? 2 : 1);
        });
        mapRef.current.setLevel(5);
        mapRef.current.setCenter(new maps.LatLng(beach.lat, beach.lng));
    }, [selectedCode, status]);

    const showAll = () => {
        const maps = window.kakao.maps;
        const bounds = new maps.LatLngBounds();
        BEACHES.forEach((beach) => bounds.extend(new maps.LatLng(beach.lat, beach.lng)));
        mapRef.current.setBounds(bounds);
    };
    const showSelected = () => {
        const beach = BEACHES.find((entry) => entry.code === selectedCode);
        mapRef.current.setLevel(5);
        mapRef.current.setCenter(new window.kakao.maps.LatLng(beach.lat, beach.lng));
    };
    return (
        <MapPanel>
            <div className="map-canvas" ref={containerRef} role="region" aria-label="해수욕장 선택 지도. 이름 검색으로도 선택할 수 있습니다." />
            {status === "ready" && <div className="map-actions"><button type="button" onClick={showAll}>전국 보기</button><button type="button" onClick={showSelected}>선택한 해변</button></div>}
            {status !== "ready" && <div className="map-message" role="status">
                <strong>{status === "loading" ? "지도를 불러오고 있어요" : "지도를 불러오지 못했어요"}</strong>
                <p>{status === "loading" ? "잠시만 기다려 주세요." : "이름 검색으로 해수욕장을 선택할 수 있습니다. 지도 연결과 카카오 지도 설정을 확인해 주세요."}</p>
                {status === "error" && <button type="button" onClick={() => setAttempt((value) => value + 1)}>지도 다시 불러오기</button>}
            </div>}
        </MapPanel>
    );
};

